#!/usr/bin/env node
// Deterministic code generator for @morehao/trendradar-contract.
//
// The contract schemas are a small, controlled JSON-Schema set. Rather than
// pull in generators that mishandle `allOf`/cross-file `$ref` (see design P0-10
// Plan B), this script emits the Go structs and TypeScript types directly from
// schema/*.v2.json. Output is deterministic so `make generate && git diff` is a
// stable CI gate.
//
// Emits:
//   contract.gen.go        Go structs + ErrorCode + ErrorCatalog (package contract)
//   gen/ts/index.d.ts      TypeScript types + runtime export declarations
//   gen/ts/index.js        ESM runtime: validators (ajv), errorCatalog, fixtures, rawSchema
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { execFileSync } from 'node:child_process'

const here = path.dirname(fileURLToPath(import.meta.url))
const ROOT = path.dirname(here)
const SCHEMA = path.join(ROOT, 'schema')
const load = (f) => JSON.parse(fs.readFileSync(path.join(SCHEMA, f), 'utf8'))

const CONTRACT_VERSION = '0.2.0'

// schema file -> optional name for a top-level (non-$defs) object root
const FILES = [
  { f: 'model.v2.json' },
  { f: 'ipc.v2.json' },
  { f: 'digest.v2.json', root: 'Digest' },
  { f: 'version-info.v2.json', root: 'VersionInfo' },
  { f: 'errors.v2.json' },
]

const schemas = Object.fromEntries(FILES.map((x) => [x.f, load(x.f)]))

const refName = (ref) => {
  const tail = ref.split('#').pop()
  return tail.split('/').filter(Boolean).pop()
}

// ---------- shared: collect named definitions ----------
// name -> { schema, file } ; first definition wins for a given name (dedupe ErrorCode)
const defs = new Map()
for (const { f } of FILES) {
  const defsObj = schemas[f].$defs || {}
  for (const [name, sch] of Object.entries(defsObj)) {
    if (!defs.has(name)) defs.set(name, sch)
  }
}

// ---------- TypeScript ----------
function tsType(s) {
  if (!s) return 'unknown'
  if (s.$ref) return refName(s.$ref)
  if (s.const !== undefined) return JSON.stringify(s.const)
  if (s.enum) return s.enum.map((e) => JSON.stringify(e)).join(' | ')
  if (s.type === 'array') return `Array<${tsType(s.items)}>`
  if (s.type === 'integer' || s.type === 'number') return 'number'
  if (s.type === 'boolean') return 'boolean'
  if (s.type === 'object') return '{ [k: string]: unknown }'
  if (s.type === 'string') return 'string'
  return 'unknown'
}

function tsProps(properties = {}, required = [], additionalProperties = false, indent = '  ') {
  const req = new Set(required)
  const lines = []
  for (const [name, prop] of Object.entries(properties)) {
    const opt = req.has(name) ? '' : '?'
    lines.push(`${indent}${JSON.stringify(name)}${opt}: ${tsType(prop)};`)
  }
  if (additionalProperties) lines.push(`${indent}[k: string]: unknown;`)
  return lines.join('\n')
}

function emitTs() {
  const out = []
  out.push('// Code generated by scripts/generate.mjs; DO NOT EDIT.')
  out.push('')
  for (const [name, sch] of defs) {
    if (sch.allOf) {
      const base = refName(sch.allOf[0].$ref)
      const extra = sch.allOf[1] || { properties: {}, required: [] }
      out.push(`export type ${name} = ${base} & {`)
      out.push(tsProps(extra.properties, extra.required, extra.additionalProperties))
      out.push('};')
      out.push('')
    } else if (sch.enum) {
      out.push(`export type ${name} = ${sch.enum.map((e) => JSON.stringify(e)).join(' | ')};`)
      out.push('')
    } else if (sch.type === 'object') {
      out.push(`export interface ${name} {`)
      out.push(tsProps(sch.properties, sch.required, sch.additionalProperties))
      out.push('}')
      out.push('')
    }
  }
  for (const { f, root } of FILES) {
    if (!root) continue
    const sch = schemas[f]
    out.push(`export interface ${root} {`)
    out.push(tsProps(sch.properties, sch.required, sch.additionalProperties))
    out.push('}')
    out.push('')
  }
  out.push('export declare const contractVersion: string;')
  out.push('export declare const errorCatalog: Record<ErrorCode, { retriable: boolean; description: string }>;')
  out.push('export declare const fixtures: {')
  out.push('  normal: Digest;')
  out.push('  degraded: Digest;')
  out.push('  emptyLang: Digest;')
  out.push('  missingOptional: Digest;')
  out.push('};')
  out.push('export declare const validators: {')
  out.push('  runRequest: (value: unknown) => boolean;')
  out.push('  runResult: (value: unknown) => boolean;')
  out.push('  digest: (value: unknown) => boolean;')
  out.push('  versionInfo: (value: unknown) => boolean;')
  out.push('};')
  out.push('export declare const rawSchema: {')
  out.push('  model: object; ipc: object; digest: object; errors: object; versionInfo: object; api: string;')
  out.push('};')
  out.push('')
  return out.join('\n')
}

// ---------- Go ----------
const GO_OVERRIDE = {
  url: 'URL',
  ok: 'OK',
  sha256: 'SHA256',
  ipcSchema: 'IPCSchema',
  prUrl: 'PRUrl',
}
const goName = (prop) => GO_OVERRIDE[prop] || prop.charAt(0).toUpperCase() + prop.slice(1)

function goType(s, required) {
  if (!s) return 'any'
  if (s.$ref) {
    const n = refName(s.$ref)
    return required ? n : '*' + n
  }
  if (s.const !== undefined) return 'int'
  if (s.enum) return required ? 'string' : '*string'
  if (s.type === 'array') return '[]' + goType(s.items, true)
  if (s.type === 'integer' || s.type === 'number') return required ? 'int' : '*int'
  if (s.type === 'boolean') return required ? 'bool' : '*bool'
  if (s.type === 'object') return 'map[string]any'
  if (s.type === 'string') {
    const base = s.format === 'date-time' ? 'time.Time' : 'string'
    return required ? base : '*' + base
  }
  return 'any'
}

function goFields(properties = {}, required = [], indent = '\t') {
  const req = new Set(required)
  const lines = []
  for (const [name, prop] of Object.entries(properties)) {
    const r = req.has(name)
    const tag = r ? `json:"${name}"` : `json:"${name},omitempty"`
    lines.push(`${indent}${goName(name)} ${goType(prop, r)} \`${tag}\``)
  }
  return lines
}

function emitGo() {
  const errorSchema = schemas['errors.v2.json']
  const errorCodes = Object.keys(errorSchema.properties)
  const out = []
  out.push('// Code generated by scripts/generate.mjs; DO NOT EDIT.')
  out.push('')
  out.push('package contract')
  out.push('')
  out.push('import "time"')
  out.push('')
  // ErrorCode enum + constants
  const codeDef = defs.get('ErrorCode')
  out.push('// ErrorCode is a stable, machine-readable error code carried over IPC.')
  out.push('type ErrorCode string')
  out.push('')
  out.push('const (')
  for (const c of codeDef.enum) out.push(`\tErrorCode${c} ErrorCode = "${c}"`)
  out.push(')')
  out.push('')
  // structs
  for (const [name, sch] of defs) {
    if (name === 'ErrorCode') continue
    if (sch.allOf) {
      const base = refName(sch.allOf[0].$ref)
      const extra = sch.allOf[1] || { properties: {}, required: [] }
      out.push(`// ${name} composes ${base} with the digest-only summary fields.`)
      out.push(`type ${name} struct {`)
      out.push(`\t${base}`)
      out.push(...goFields(extra.properties, extra.required))
      out.push('}')
      out.push('')
    } else if (sch.type === 'object') {
      out.push(`type ${name} struct {`)
      out.push(...goFields(sch.properties, sch.required))
      out.push('}')
      out.push('')
    }
  }
  for (const { f, root } of FILES) {
    if (!root) continue
    const sch = schemas[f]
    out.push(`type ${root} struct {`)
    out.push(...goFields(sch.properties, sch.required))
    out.push('}')
    out.push('')
  }
  // ErrorCatalog
  out.push('// ErrorCatalog is the single source of truth for error retriability.')
  out.push('var ErrorCatalog = map[ErrorCode]ErrorMeta{')
  for (const c of errorCodes) {
    const meta = errorSchema.properties[c].properties
    out.push(`\tErrorCode${c}: {Retriable: ${meta.retriable.const}, Description: ${JSON.stringify(meta.description.const)}},`)
  }
  out.push('}')
  out.push('')
  out.push('// Valid reports whether c is a canonical code.')
  out.push('func (c ErrorCode) Valid() bool { _, ok := ErrorCatalog[c]; return ok }')
  out.push('')
  out.push('// Retriable reports whether the caller may retry an operation that failed with c.')
  out.push('func (c ErrorCode) Retriable() bool { m, ok := ErrorCatalog[c]; return ok && m.Retriable }')
  out.push('')
  return out.join('\n')
}

// ---------- TS runtime (index.js) ----------
function emitTsRuntime() {
  const fixturesDir = path.join(ROOT, 'fixtures')
  const readFixture = (n) => JSON.parse(fs.readFileSync(path.join(fixturesDir, n), 'utf8'))
  const fixtures = {
    normal: readFixture('digest-normal.json'),
    degraded: readFixture('digest-degraded.json'),
    emptyLang: readFixture('digest-empty-lang.json'),
    missingOptional: readFixture('digest-missing-optional.json'),
  }
  const errorSchema = schemas['errors.v2.json']
  const errorCatalog = {}
  for (const c of Object.keys(errorSchema.properties)) {
    const meta = errorSchema.properties[c].properties
    errorCatalog[c] = { retriable: meta.retriable.const, description: meta.description.const }
  }
  const api = fs.readFileSync(path.join(SCHEMA, 'api.v2.yaml'), 'utf8')
  const model = schemas['model.v2.json']
  const ipc = schemas['ipc.v2.json']
  const digestRaw = schemas['digest.v2.json']
  const versionInfo = schemas['version-info.v2.json']
  // rewrite digest's relative ref to the model $id so ajv can resolve it
  const digest = JSON.parse(
    JSON.stringify(digestRaw).replaceAll('"model.v2.json#/$defs/RepoDigest"', JSON.stringify(model.$id + '#/$defs/RepoDigest')),
  )
  const j = (v) => JSON.stringify(v, null, 2)
  return `// Code generated by scripts/generate.mjs; DO NOT EDIT.
import Ajv from 'ajv/dist/2020.js'
import addFormats from 'ajv-formats'

export const contractVersion = ${JSON.stringify(CONTRACT_VERSION)}

export const errorCatalog = ${j(errorCatalog)}

export const fixtures = ${j(fixtures)}

const model = ${j(model)}
const ipc = ${j(ipc)}
const digest = ${j(digest)}
const versionInfo = ${j(versionInfo)}
const errors = ${j(errorSchema)}
const api = ${JSON.stringify(api)}

export const rawSchema = { model, ipc, digest, errors, versionInfo, api }

const ajv = new Ajv({ allErrors: true, strict: false })
addFormats(ajv)
ajv.addSchema(model)
ajv.addSchema(ipc)
ajv.addSchema(digest)
ajv.addSchema(versionInfo)

export const validators = {
  runRequest: ajv.compile({ $ref: ipc.$id + '#/$defs/RunRequest' }),
  runResult: ajv.compile({ $ref: ipc.$id + '#/$defs/RunResult' }),
  digest: ajv.getSchema(digest.$id),
  versionInfo: ajv.getSchema(versionInfo.$id),
}
`
}

// ---------- write ----------
fs.writeFileSync(path.join(ROOT, 'contract.gen.go'), emitGo())
execFileSync('gofmt', ['-w', path.join(ROOT, 'contract.gen.go')])
fs.mkdirSync(path.join(ROOT, 'gen', 'ts'), { recursive: true })
fs.writeFileSync(path.join(ROOT, 'gen', 'ts', 'index.d.ts'), emitTs())
fs.writeFileSync(path.join(ROOT, 'gen', 'ts', 'index.js'), emitTsRuntime())
console.log('generated contract.gen.go, gen/ts/index.d.ts, gen/ts/index.js')
